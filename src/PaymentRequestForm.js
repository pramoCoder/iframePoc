const buildDefaultPayload = () =>
  PAYLOAD_FIELDS.reduce((values, field) => {
    if (!field.fromSearch && !field.hidden) {
      values[field.key] = field.defaultValue;
    }
    return values;
  }, {});

const requireText = (errors, values, key) => {
  if (!values[key].trim()) {
    errors[key] = `${key} is required.`;
  }
};

const validatePayload = (values, partyId) => {
  const errors = {};

  if (!partyId) {
    errors.customerId = "Select a customer from the search results.";
  }

  if (!/^[1-9]\d*$/.test(values.amount.trim())) {
    errors.amount = "amount must be a whole number of cents greater than zero.";
  }

  requireText(errors, values, "brand");

  if (!/^[A-Z]{3}$/.test(values.currency.trim())) {
    errors.currency = "currency must be a 3-letter code such as AUD.";
  }

  const expiry = values.expiry.trim();
  if (!ISO_UTC_PATTERN.test(expiry) || Number.isNaN(Date.parse(expiry))) {
    errors.expiry =
      "expiry must be an ISO-8601 UTC timestamp, for example 2026-10-08T00:03:13.974Z.";
  }

  requireText(errors, values, "kid");
  requireText(errors, values, "paymentIntent");
  requireText(errors, values, "paymentMethod");
  requireText(errors, values, "paymentReference");
  requireText(errors, values, "product");
  requireText(errors, values, "policyNumber");
  requireText(errors, values, "quoteNumber");

  if (!/^(PC|BC)$/.test(values.sourceSystem.trim())) {
    errors.sourceSystem = "sourceSystem must be PC or BC.";
  }

  requireText(errors, values, "staffNumber");

  if (!UUID_PATTERN.test(values.correlationId.trim())) {
    errors.correlationId = "correlationId must be a UUID.";
  }

  return errors;
};

const buildPaymentUrl = (values, partyId) => {
  const url = new URL(PAYMENT_PAGE_URL);

  PAYLOAD_FIELDS.forEach((field) => {
    const value = field.fromSearch
      ? partyId
      : field.hidden
        ? field.defaultValue
        : values[field.key].trim();
    url.searchParams.set(field.key, value);
  });

  url.searchParams.set("id", partyId);
  return url.toString();
};

function PaymentRequestForm({ partyId, showMissingPartyAlert, onValidSubmit }) {
  const [formValues, setFormValues] = useState(buildDefaultPayload);
  const [fieldErrors, setFieldErrors] = useState({});

  useEffect(() => {
    setFieldErrors((current) => ({ ...current, customerId: "" }));
  }, [partyId]);

  const handleFieldChange = (event) => {
    const { name, value } = event.target;
    setFormValues((current) => ({ ...current, [name]: value }));
    setFieldErrors((current) => ({ ...current, [name]: "" }));
  };

  const handleSubmit = (event) => {
    event.preventDefault();
    const errors = validatePayload(formValues, partyId);
    setFieldErrors(errors);

    if (Object.keys(errors).length > 0) {
      return;
    }

    onValidSubmit(buildPaymentUrl(formValues, partyId));
  };

  const hasFieldErrors = Object.values(fieldErrors).some(Boolean);

  return (
    <>
      <Typography variant="subtitle1" gutterBottom>
        Pay Now Request
      </Typography>
      <Typography variant="body2" color="text.secondary" sx={{ mb: 2 }}>
        customerId is filled from the selected customer's partyId. Submit to load the payment iframe.
      </Typography>

      {showMissingPartyAlert && (
        <Alert severity="error" sx={{ mb: 2 }}>
          Unable to load payment setup: Guidewire Id is missing for this customer.
        </Alert>
      )}

      <Box component="form" noValidate onSubmit={handleSubmit}>
        <Grid container spacing={2}>
          {PAYLOAD_FIELDS.filter((field) => !field.hidden).map((field) => (
            <Grid item xs={12} sm={6} key={field.key}>
              <TextField
                label={field.key}
                name={field.key}
                value={field.fromSearch ? partyId : formValues[field.key]}
                onChange={field.fromSearch ? undefined : handleFieldChange}
                error={Boolean(fieldErrors[field.key])}
                helperText={fieldErrors[field.key] || field.description}
                fullWidth
                size="small"
                InputProps={field.fromSearch ? { readOnly: true } : undefined}
              />
            </Grid>
          ))}
          <Grid item xs={12}>
            {hasFieldErrors && (
              <Alert severity="error" sx={{ mb: 2 }}>
                Fix the highlighted fields before loading the payment iframe.
              </Alert>
            )}
            <Button type="submit" variant="contained">
              Submit
            </Button>
          </Grid>
        </Grid>
      </Box>
    </>
  );
}

export default PaymentRequestForm;
